// @vitest-environment node
//
// Real @ton/crypto uses tweetnacl, whose `instanceof Uint8Array` check fails
// when jsdom + vite-plugin-node-polyfills hand it a polyfilled Uint8Array
// from a different realm. Derivation (mnemonic -> key pair -> address) is a
// pure crypto path, so it runs under the node environment where the realm
// matches. WalletContractV4.create is covered separately in
// wallet.service.contract.test.ts because @ton/core's `buffer` import is the
// polyfill build and does not accept a Node-realm Buffer under vitest.
import { describe, it, expect, beforeAll } from 'vitest';
import { Address } from '@ton/core';
import { TonClient } from '@ton/ton';
import { walletService } from '../wallet.service';

let mnemonic: string[];

beforeAll(async () => {
  // Generated by the real @ton/crypto implementation under test.
  const { mnemonicNew } = await import('@ton/crypto');
  mnemonic = await mnemonicNew(24);
});

describe('walletService.createWallet', () => {
  it('TC_WALLETSVC_CREATE_001 returns a 24-word mnemonic', async () => {
    const wallet = await walletService.createWallet();
    expect(wallet.mnemonic).toHaveLength(24);
    expect(wallet.mnemonic.every(w => typeof w === 'string' && w.length > 0)).toBe(true);
  });

  it('TC_WALLETSVC_CREATE_002 returns a valid testnet non-bounceable address', async () => {
    const wallet = await walletService.createWallet();
    expect(wallet.address).toHaveLength(48);
    expect(wallet.address.startsWith('0Q') || wallet.address.startsWith('UQ')).toBe(true);
    expect(() => Address.parse(wallet.address)).not.toThrow();
  });

  it('TC_WALLETSVC_CREATE_003 returns a 64-char hex public key', async () => {
    const wallet = await walletService.createWallet();
    expect(wallet.publicKey).toMatch(/^[0-9a-f]{64}$/);
  });

  it('TC_WALLETSVC_CREATE_004 generates distinct wallets', async () => {
    const a = await walletService.createWallet();
    const b = await walletService.createWallet();
    expect(a.mnemonic).not.toEqual(b.mnemonic);
    expect(a.address).not.toBe(b.address);
  }, 20_000);
});

describe('walletService.importWallet', () => {
  it('TC_WALLETSVC_IMPORT_001 is deterministic for the same mnemonic', async () => {
    const a = await walletService.importWallet(mnemonic);
    const b = await walletService.importWallet(mnemonic);
    expect(a.address).toBe(b.address);
    expect(a.publicKey).toBe(b.publicKey);
  });

  it('TC_WALLETSVC_IMPORT_002 returns the mnemonic it was given', async () => {
    const wallet = await walletService.importWallet(mnemonic);
    expect(wallet.mnemonic).toEqual(mnemonic);
  });
});

describe('walletService.getKeyPair', () => {
  it('TC_WALLETSVC_KEYPAIR_001 derives a key pair with 32-byte public key', async () => {
    const keyPair = await walletService.getKeyPair(mnemonic);
    expect(keyPair.publicKey).toHaveLength(32);
    expect(keyPair.secretKey).toHaveLength(64);
  });

  it('TC_WALLETSVC_KEYPAIR_002 matches the imported wallet public key', async () => {
    const keyPair = await walletService.getKeyPair(mnemonic);
    const wallet = await walletService.importWallet(mnemonic);
    expect(Buffer.from(keyPair.publicKey).toString('hex')).toBe(wallet.publicKey);
  });
});

describe('walletService.getClient', () => {
  it('TC_WALLETSVC_CLIENT_001 returns a TonClient instance', () => {
    const client = walletService.getClient();
    expect(client).toBeInstanceOf(TonClient);
    expect(typeof client.getBalance).toBe('function');
  });
});
